const { app, BrowserWindow } = require('electron');
const path = require('path'); const fs = require('fs');
const ROOT = path.join(__dirname, '..'); const OUT = path.join(ROOT,'screenshots_v3');
app.setPath('userData', path.join(process.env.TEMP || '.', 'cp-tb-' + Date.now()));
app.commandLine.appendSwitch('disable-gpu'); app.commandLine.appendSwitch('no-sandbox');
const sleep = ms => new Promise(r => setTimeout(r, ms));
const out = {}; const fails = [];
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1920, height: 1080, show: true, webPreferences: { contextIsolation: true, backgroundThrottling: false } });
  win.setContentSize(1920,1080); win.setAlwaysOnTop(true); win.focus();
  const js = async (l, c) => { try { return await win.webContents.executeJavaScript(c, true); } catch (e) { fails.push(l + ':' + String(e.message||e).slice(0,50)); return null; } };
  const errs = [];
  win.webContents.on('console-message', function(){ var a=[].slice.call(arguments); var d=a[1]; var lvl=(typeof d==='object'&&d)?d.level:a[1]; var m=(typeof d==='object'&&d)?d.message:a[2]; if(lvl==='error'||lvl===3) errs.push(String(m).slice(0,120)); });
  await win.loadURL('file://' + path.join(ROOT, 'design', 'v3_teacher_desk.html').replace(/\\/g, '/'));
  await sleep(1500);
  out.toolbar = await js('tb', `(function(){var t=document.getElementById('toolbar');return [].slice.call(t.querySelectorAll('button,input')).map(function(e){return e.id||e.className});})()`);
  out.gone = await js('gone', `(function(){return {clear:!!document.getElementById('btn-clear-sel'),move:!!document.getElementById('btn-move-group'),strip:!!document.querySelector('.strip-right')};})()`);
  await js('pick', `(function(){var r=document.querySelectorAll('.stu-row');r[0].click();r[1].click();})()`);
  await sleep(300);
  out.selected = await js('sel', `document.querySelectorAll('.is-selected,.selected').length`);
  await js('clear', `document.getElementById('sel-clear').click()`);
  await sleep(300);
  out.afterRailClear = await js('ac', `(function(){return {sel:document.querySelectorAll('.is-selected,.selected').length,count:(document.getElementById('sel-count')||{}).textContent};})()`);
  out.audit = await js('audit', `(function(){var a=window.__v3audit?window.__v3audit():null;return a?{pass:a.pass,occluded:(a.occluded||[]).length,missing:(a.missing||[]).length}:null;})()`);
  const im = await win.webContents.capturePage(); fs.writeFileSync(path.join(OUT,'teacher_visual_09_toolbar.png'), im.toPNG());
  out.errors = errs.slice(0,4); out.fails = fails;
  fs.writeFileSync(path.join(OUT,'teacher_toolbar_check.json'), JSON.stringify(out,null,2));
  console.log('done'); app.quit();
});
