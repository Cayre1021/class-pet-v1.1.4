const { app, BrowserWindow } = require('electron');
const path = require('path'); const fs = require('fs');
const ROOT = path.join(__dirname, '..'); const OUT = path.join(ROOT,'screenshots_v3');
app.setPath('userData', path.join(process.env.TEMP || '.', 'cp-pill-' + Date.now()));
app.commandLine.appendSwitch('disable-gpu'); app.commandLine.appendSwitch('no-sandbox');
const sleep = ms => new Promise(r => setTimeout(r, ms));
const out = {}; const fails = [];
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1920, height: 1080, show: true, webPreferences: { contextIsolation: true, backgroundThrottling: false } });
  win.setContentSize(1920,1080); win.setAlwaysOnTop(true); win.focus();
  const js = async (l, c) => { try { return await win.webContents.executeJavaScript(c, true); } catch (e) { fails.push(l); return null; } };
  const errs = [];
  win.webContents.on('console-message', function(){ var a=[].slice.call(arguments); var d=a[1]; var lvl=(typeof d==='object'&&d)?d.level:a[1]; var m=(typeof d==='object'&&d)?d.message:a[2]; if(lvl==='error'||lvl===3) errs.push(String(m).slice(0,120)); });
  await win.loadURL('file://' + path.join(ROOT, 'design', 'v3_teacher_desk.html').replace(/\\/g, '/'));
  await sleep(1500);
  out.portalBtn = await js('pb', `(function(){var a=document.getElementById('btn-portal');return {text:a.textContent.replace(/\\s+/g,' ').trim(),href:a.getAttribute('href'),cls:a.className};})()`);
  out.pillBefore = await js('p0', `(function(){var p=document.getElementById('sel-pill');return p?{hidden:p.hidden}:null;})()`);
  await js('pick', `(function(){var r=document.querySelectorAll('.stu-row');r[0].click();r[1].click();r[2].click();})()`);
  await sleep(400);
  out.pillAfter = await js('p1', `(function(){var p=document.getElementById('sel-pill');return p?{hidden:p.hidden,text:p.textContent.replace(/\\s+/g,' ').trim(),rect:(function(){var x=p.getBoundingClientRect();return [Math.round(x.left),Math.round(x.top),Math.round(x.width),Math.round(x.height)];})()}:null;})()`);
  const im = await win.webContents.capturePage(); fs.writeFileSync(path.join(OUT,'teacher_visual_10_pill.png'), im.toPNG());
  await js('clear', `document.getElementById('sel-pill-clear').click()`);
  await sleep(400);
  out.pillCleared = await js('p2', `(function(){var p=document.getElementById('sel-pill');return {hidden:p.hidden,sel:document.querySelectorAll('.is-selected,.selected').length};})()`);
  out.audit = await js('audit', `(function(){var a=window.__v3audit?window.__v3audit():null;return a?{pass:a.pass,occluded:(a.occluded||[]).length,missing:(a.missing||[]).length}:null;})()`);
  out.errors = errs.slice(0,4); out.fails = fails;
  fs.writeFileSync(path.join(OUT,'pill_check.json'), JSON.stringify(out,null,2));
  console.log('done'); app.quit();
});
