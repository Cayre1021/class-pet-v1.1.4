const { app, BrowserWindow } = require('electron');
const path = require('path'); const fs = require('fs');
const ROOT = path.join(__dirname, '..', '..'); const OUT = path.join(ROOT,'screenshots_v3');
app.setPath('userData', path.join(process.env.TEMP || '.', 'cp-p3-' + Date.now()));
app.commandLine.appendSwitch('disable-gpu'); app.commandLine.appendSwitch('no-sandbox');
const sleep = ms => new Promise(r => setTimeout(r, ms));
app.whenReady().then(async () => {
  const out = {};
  const win = new BrowserWindow({ width: 1920, height: 1080, show: true, webPreferences: { contextIsolation: true, backgroundThrottling: false } });
  win.setContentSize(1920,1080); win.setAlwaysOnTop(true); win.focus();
  const js = c => win.webContents.executeJavaScript(c, true);
  const errs = [];
  win.webContents.on('console-message', function(){ var a=[].slice.call(arguments); var d=a[1]; var lvl=(typeof d==='object'&&d)?d.level:a[1]; var m=(typeof d==='object'&&d)?d.message:a[2]; if(lvl==='error'||lvl===3) errs.push(String(m).slice(0,120)); });
  const shot = async n => { win.webContents.invalidate(); await sleep(260); const im = await win.webContents.capturePage(); fs.writeFileSync(path.join(OUT,'portal_visual_'+n+'.png'), im.toPNG()); };
  await win.loadURL('file://' + path.join(ROOT, 'design', 'v3_portal.html').replace(/\\/g, '/'));
  await sleep(1600);
  out.base2 = await js(`(function(){var d=document.documentElement,t=document.body.innerText;return {docH:d.scrollHeight,innerH:innerHeight,docW:d.scrollWidth,innerW:innerWidth,hasPetText:/本班宠物|只在线/.test(t)};})()`);
  await shot('01_login');
  await js(`document.getElementById('tab-register').click()`);
  await sleep(400);
  out.register = await js(`(function(){var ids=['rg-class','rg-name','rg-phone','rg-pw','rg-pw2','rg-subject'];var found={};ids.forEach(function(i){found[i]=!!document.getElementById(i)});var lab=[].slice.call(document.querySelectorAll('#panel-register label')).map(function(l){return l.textContent.trim()}).slice(0,8);return {found:found,labels:lab};})()`);
  await shot('02_register');
  const fill = await js(`(function(){
    function set(id,v){var e=document.getElementById(id);if(!e)return false;e.value=v;e.dispatchEvent(new Event('input',{bubbles:true}));return true;}
    var ok=[set('rg-class','三年级二班'),set('rg-name','李青'),set('rg-phone','13800138000'),set('rg-pw','pet2024'),set('rg-pw2','pet2024')];
    var sub=document.querySelector('#rg-subject [data-subject="语文"],#rg-subject button');
    if(sub)sub.click();
    return ok.join(',');
  })()`);
  out.fill = fill;
  await sleep(200);
  await js(`(function(){var p=document.getElementById('panel-register');(p.querySelector('button[type=submit]')||p.querySelector('button.btn-primary')).click();})()`);
  await sleep(800);
  out.afterRegister = await js(`(function(){var store=localStorage.getItem('classpet.teacher.profile.v3');var done=document.getElementById('panel-done');var chip=document.querySelector('.whoami,.chip,.who');return {stored:store?JSON.parse(store):null,session:localStorage.getItem('classpet.teacher.session.v3'),doneShown:done?getComputedStyle(done).display!=='none'&&!done.hasAttribute('hidden'):null,chipText:chip?chip.textContent.replace(/\\s+/g,' ').trim():null};})()`);
  await shot('03_done');
  await win.reload();
  await sleep(1600);
  out.afterReload = await js(`(function(){var done=document.getElementById('panel-done');var t=document.body.innerText;return {doneShown:done?!done.hasAttribute('hidden'):null,hasChip:/三年级二班/.test(t)&&/李青/.test(t),hasExit:/退出/.test(t),gates:[].slice.call(document.querySelectorAll('a.gate')).map(function(a){return a.getAttribute('href')}),docH:document.documentElement.scrollHeight,innerH:innerHeight};})()`);
  await shot('04_persisted');
  out.errors = errs.slice(0,5);
  fs.writeFileSync(path.join(OUT,'portal_check3.json'), JSON.stringify(out,null,2));
  console.log('done'); app.quit();
});
