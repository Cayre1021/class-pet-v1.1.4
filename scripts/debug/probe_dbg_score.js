const { app, BrowserWindow } = require('electron');
const path = require('path'); const fs = require('fs');
const ROOT = path.join(__dirname, '..', '..');
app.setPath('userData', path.join(process.env.TEMP || '.', 'cp-dbg9-' + Date.now()));
app.commandLine.appendSwitch('disable-gpu'); app.commandLine.appendSwitch('no-sandbox');
const sleep = ms => new Promise(r => setTimeout(r, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1920, height: 1080, show: false, webPreferences: { contextIsolation: true, backgroundThrottling: false } });
  const js = c => win.webContents.executeJavaScript(c, true);
  await win.loadURL('file://' + path.join(ROOT, 'design', 'v3_teacher_desk.html').replace(/\\/g, '/'));
  await sleep(1400);
  await js(`window.__e=[];window.addEventListener('error',function(e){window.__e.push((e.message||'')+' @@ '+(e.error&&e.error.stack?e.error.stack.split('\\n').slice(0,4).join(' | '):''));});0;`);
  await js(`(function(){var r=document.querySelectorAll('.stu-row');r[0].click();})()`);
  await sleep(300);
  await js(`(function(){var b=document.querySelector('[data-score="3"]');b.click();})()`);
  await sleep(600);
  const out = await js(`(function(){return {errs:window.__e,sel:document.querySelectorAll('.is-selected,.selected').length,toast:(document.getElementById('toast-text')||{}).textContent};})()`);
  fs.writeFileSync(path.join(ROOT,'screenshots_v3','dbg_score.json'), JSON.stringify(out,null,2));
  console.log('done'); app.quit();
});
