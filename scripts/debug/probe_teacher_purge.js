const { app, BrowserWindow } = require('electron');
const path = require('path'); const fs = require('fs');
const ROOT = path.join(__dirname, '..', '..'); const OUT = path.join(ROOT,'screenshots_v3');
app.setPath('userData', path.join(process.env.TEMP || '.', 'cp-smk2-' + Date.now()));
app.commandLine.appendSwitch('disable-gpu'); app.commandLine.appendSwitch('no-sandbox');
const sleep = ms => new Promise(r => setTimeout(r, ms));
const out = {}; const fails = [];
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1920, height: 1080, show: true, webPreferences: { contextIsolation: true, backgroundThrottling: false } });
  win.setContentSize(1920,1080); win.setAlwaysOnTop(true); win.focus();
  const js = async (l, c) => { try { return await win.webContents.executeJavaScript(c, true); } catch (e) { fails.push(l + ':' + String(e.message||e).slice(0,60)); return null; } };
  const errs = [];
  win.webContents.on('console-message', function(){ var a=[].slice.call(arguments); var d=a[1]; var lvl=(typeof d==='object'&&d)?d.level:a[1]; var m=(typeof d==='object'&&d)?d.message:a[2]; if(lvl==='error'||lvl===3) errs.push(String(m).slice(0,120)); });
  await win.loadURL('file://' + path.join(ROOT, 'design', 'v3_teacher_desk.html').replace(/\\/g, '/'));
  await sleep(1500);
  out.rows = await js('rows', `document.querySelectorAll('.stu-row').length`);
  out.pick = await js('pick', `(function(){var r=document.querySelectorAll('.stu-row');r[0].click();r[1].click();return document.querySelectorAll('.is-selected,.selected').length;})()`);
  out.scoreBtn = await js('scorebtn', `(function(){var b=document.querySelector('[data-score="3"]');if(!b)return 'none';return b.getAttribute('data-rule');})()`);
  await js('score', `(function(){var b=document.querySelector('[data-score="3"]');if(b)b.click();})()`);
  await sleep(500);
  out.scoreToast = await js('toast', `(function(){var t=document.getElementById('toast-text');return t?t.textContent.trim().slice(0,40):null;})()`);
  await js('menu', `document.querySelector('.stu-more').click()`);
  await sleep(300);
  out.menuItems = await js('menuitems', `(function(){var m=document.getElementById('row-menu');return m?[].slice.call(m.querySelectorAll('button')).map(function(b){return b.textContent.replace(/\\s+/g,' ').trim()}):null;})()`);
  const im = await win.webContents.capturePage(); fs.writeFileSync(path.join(OUT,'teacher_visual_08_after_purge.png'), im.toPNG());
  out.errors = errs.slice(0,5); out.fails = fails;
  fs.writeFileSync(path.join(OUT,'teacher_purge_check.json'), JSON.stringify(out,null,2));
  console.log('done'); app.quit();
});
