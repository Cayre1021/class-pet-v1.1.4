const { app, BrowserWindow } = require('electron');
const path = require('path'); const fs = require('fs');
const ROOT = path.join(__dirname, '..', '..'); const OUT = path.join(ROOT,'screenshots_v3');
app.setPath('userData', path.join(process.env.TEMP || '.', 'cp-p7-' + Date.now()));
app.commandLine.appendSwitch('disable-gpu'); app.commandLine.appendSwitch('no-sandbox');
const sleep = ms => new Promise(r => setTimeout(r, ms));
const out = {}; const fails = [];
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1920, height: 1080, show: true, webPreferences: { contextIsolation: true, backgroundThrottling: false } });
  win.setContentSize(1920,1080); win.setAlwaysOnTop(true); win.focus();
  const js = async (l, c) => { try { return await win.webContents.executeJavaScript(c, true); } catch (e) { fails.push(l + ':' + String(e.message||e).slice(0,60)); return null; } };
  await win.loadURL('file://' + path.join(ROOT, 'design', 'v3_portal.html').replace(/\\/g, '/'));
  await sleep(1500);
  await js('tab', `document.getElementById('tab-register').click()`);
  await sleep(300);
  await js('reg', `(function(){function s(id,v){var e=document.getElementById(id);e.value=v;e.dispatchEvent(new Event('input',{bubbles:true}));}s('rg-class','三年级二班');s('rg-name','李青');var r=document.querySelector('input[name=subject][value=\\"语文\\"]');r.click();var p=document.getElementById('panel-register');(p.querySelector('button[type=submit]')||p.querySelector('.btn-primary')).click();})()`);
  await sleep(800);
  out.afterRegister = await js('ar', `(function(){return {done:!document.getElementById('panel-done').hasAttribute('hidden'),stored:localStorage.getItem('classpet.teacher.profile.v3')};})()`);
  await js('switch', `document.getElementById('switch').click()`);
  await sleep(500);
  out.afterSwitch = await js('as', `(function(){return {cls:(document.getElementById('lg-class')||{}).value,name:(document.getElementById('lg-name')||{}).value,flag:localStorage.getItem('classpet.teacher.switched.v3')};})()`);
  await win.reload();
  await sleep(1400);
  out.afterSwitchReload = await js('asr', `(function(){return {cls:(document.getElementById('lg-class')||{}).value,name:(document.getElementById('lg-name')||{}).value,doneHidden:document.getElementById('panel-done').hasAttribute('hidden')};})()`);
  await js('login', `(function(){function s(id,v){var e=document.getElementById(id);e.value=v;e.dispatchEvent(new Event('input',{bubbles:true}));}s('lg-class','三年级二班');s('lg-name','李青');var p=document.getElementById('panel-login');(p.querySelector('button[type=submit]')||p.querySelector('.btn-primary')).click();})()`);
  await sleep(800);
  out.afterLogin = await js('al', `(function(){return {done:!document.getElementById('panel-done').hasAttribute('hidden'),flag:localStorage.getItem('classpet.teacher.switched.v3')};})()`);
  await win.reload();
  await sleep(1300);
  out.afterLoginReload = await js('alr', `(function(){return {done:!document.getElementById('panel-done').hasAttribute('hidden'),cls:(document.getElementById('lg-class')||{}).value};})()`);
  out.fails = fails;
  const im = await win.webContents.capturePage(); fs.writeFileSync(path.join(OUT,'portal_visual_06_switch.png'), im.toPNG());
  fs.writeFileSync(path.join(OUT,'portal_check6.json'), JSON.stringify(out,null,2));
  console.log('done'); app.quit();
});
