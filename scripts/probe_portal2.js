const { app, BrowserWindow } = require('electron');
const path = require('path'); const fs = require('fs');
const ROOT = path.join(__dirname, '..'); const OUT = path.join(ROOT,'screenshots_v3');
app.setPath('userData', path.join(process.env.TEMP || '.', 'cp-portal2-' + Date.now()));
app.commandLine.appendSwitch('disable-gpu'); app.commandLine.appendSwitch('no-sandbox');
const sleep = ms => new Promise(r => setTimeout(r, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1920, height: 1080, show: true, webPreferences: { contextIsolation: true, backgroundThrottling: false } });
  win.setContentSize(1920,1080); win.setAlwaysOnTop(true); win.focus();
  const js = c => win.webContents.executeJavaScript(c, true);
  const shot = async n => { win.webContents.invalidate(); await sleep(250); const im = await win.webContents.capturePage(); fs.writeFileSync(path.join(OUT,'portal_visual_'+n+'.png'), im.toPNG()); };
  await win.loadURL('file://' + path.join(ROOT, 'design', 'v3_portal.html').replace(/\\/g, '/'));
  await sleep(1600);
  const out = {};
  await shot('01_login');
  await js(`(function(){var p=document.getElementById('panel-login');var b=p.querySelector('button[type=submit]')||p.querySelector('button.btn-primary');b.click();})()`);
  await sleep(400);
  out.emptyMsgs = await js(`(function(){return {id:(document.getElementById('lg-id-msg')||{}).textContent,pw:(document.getElementById('lg-pw-msg')||{}).textContent,invalid:[document.getElementById('lg-id').getAttribute('aria-invalid'),document.getElementById('lg-pw').getAttribute('aria-invalid')],badFields:document.querySelectorAll('.field.is-bad').length};})()`);
  await shot('02_login_errors');
  await js(`(function(){var t=document.getElementById('tab-register');t.click();})()`);
  await sleep(400);
  await shot('03_register');
  await js(`(function(){var id=document.getElementById('lg-id'),pw=document.getElementById('lg-pw');document.getElementById('tab-login').click();id.value='13800138000';id.dispatchEvent(new Event('input',{bubbles:true}));pw.value='pet2024';pw.dispatchEvent(new Event('input',{bubbles:true}));var p=document.getElementById('panel-login');(p.querySelector('button[type=submit]')||p.querySelector('button.btn-primary')).click();})()`);
  await sleep(700);
  await shot('04_done');
  out.gates = await js(`(function(){return [].slice.call(document.querySelectorAll('a.gate')).map(function(a){return a.getAttribute('href')});})()`);
  fs.writeFileSync(path.join(OUT,'portal_check2.json'), JSON.stringify(out,null,2));
  console.log('done'); app.quit();
});
