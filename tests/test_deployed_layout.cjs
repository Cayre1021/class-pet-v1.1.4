const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { parseHTML } = require('linkedom');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'electron-app/src/display_bigscreen_touch_pro.html'), 'utf8');
const { document } = parseHTML(source);
for (const script of document.querySelectorAll('script:not([src])')) new vm.Script(script.textContent);
const students = Array.from({length:88}, (_, i) => ({id:`s${i}`, no:String(i+1), name:`Student ${i+1}`, group:i%4+1, level:i%7, exp:i*3, activeSubject:'chinese', pets:{chinese:{subject:'语文',name:'Cat',species:'cat',isHatched:true,visualStage:1,level:i%7,exp:i*3}}}));
const store = {students, getGroupStats:()=>[1,2,3,4].map(group=>({group,totalExp:100})), isSubjectUnlocked:()=>true};
const context = vm.createContext({document,window:{},store,console,updateHeaderClassInfo(){}});
// Run the deployed render functions without booting IPC or accessing a database.
vm.runInContext(source.slice(source.indexOf('const petLayoutState ='),source.indexOf('function switchView(v)')),context);
const run = code => vm.runInContext(code,context);
run('renderGrid()');
assert.equal(document.querySelectorAll('#gridFullView .pet-card').length,88);
assert(!document.getElementById('layoutPagination'));
run("selectLayoutStudent('s70')");
assert(document.getElementById('petDetailPanel').textContent.includes('Student 71'));
assert.equal(document.querySelectorAll('#gridFullView [aria-pressed="true"]').length,1);
run("handleLayoutGroupFilter('2')");
assert.equal(document.querySelectorAll('#gridFullView .pet-card').length,22);
assert([...document.querySelectorAll('#gridFullView .pet-card')].every(card=>Number(card.dataset.studentId.slice(1))%4===1));
assert.equal(document.querySelectorAll('#gridFullView [aria-pressed="true"]').length,1);
const sortStart=source.indexOf('function sortCards(by)');
vm.runInContext(source.slice(sortStart,source.indexOf('function closeDetailsModal()',sortStart)),context);
run("handleLayoutGroupFilter('all');sortCards('level')");
assert.equal(document.querySelector('#gridFullView .pet-card').dataset.studentId, [...students].sort((a,b)=>b.level-a.level||b.exp-a.exp)[0].id);
run("sortCards('no')");
assert.equal(document.querySelector('#gridFullView .pet-card').dataset.studentId,'s0');
students[0].isArchived=true;
run('renderGrid()');
assert.equal(document.querySelectorAll('#gridFullView .pet-card').length,87);
store.students=[];
run('renderGrid()');
assert.equal(document.querySelectorAll('#gridFullView .pet-card').length,0);
assert.equal(document.getElementById('layoutResultCount').textContent,'0 位学生');
assert.equal(document.getElementById('layoutGroupTotals').children.length,0);

const portalHtml=fs.readFileSync(path.join(root,'electron-app/src/portal_auth.html'),'utf8');
const portal=parseHTML(portalHtml);
const portalContext=vm.createContext({document:portal.document});
vm.runInContext(fs.readFileSync(path.join(root,'electron-app/src/portal_background.js'),'utf8'),portalContext);
assert.equal(portal.document.querySelectorAll('.paw-print').length,10);
assert.equal(new Set([...portal.document.querySelectorAll('.paw-print')].map(p=>p.style.getPropertyValue('--paw-color'))).size,10);
assert(!portal.document.querySelector('.hub-card.primary'));
assert(portal.document.getElementById('loginAccount'));
for(const kind of ['cat','dog'])assert(fs.existsSync(path.join(root,`electron-app/src/assets/decor/${kind}-paw.svg`)));
console.log('Deployed layout: full roster, selection, group filtering, sorting, archive/empty states, portal paws and inline syntax passed. Visual/native business verification remains manual.');
