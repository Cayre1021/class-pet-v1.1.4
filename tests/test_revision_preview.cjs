const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { parseHTML } = require('linkedom');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'design/revision-preview.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'design/revision-preview.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'design/revision-preview.css'), 'utf8');
const { document, window } = parseHTML(html);
const context = vm.createContext({document,window,console});
vm.runInContext(js, context);
let checks = 0;
function check(condition, message){assert(condition, message);checks++;}
function run(code){return vm.runInContext(code,context);}
check(document.querySelectorAll('.pet-card').length===88,'all 88 pets must appear without pagination');
check(!html.includes('上一页')&&!html.includes('下一页'),'no pagination');
check(document.querySelectorAll('.group-summary>div').length===4,'four compact group totals');
run('selectStudent(17)');
check(document.getElementById('detail-name').textContent==='同学 17','selected detail updates');
check(document.querySelectorAll('.pet-card[aria-pressed="true"]').length===1,'only one pet selected');
check(document.querySelector('.pet-card[aria-pressed="true"]').dataset.student==='17','selected marker follows pet');
run("groupFilter='2';renderCollection()");
check(document.querySelectorAll('.pet-card').length===22,'group filter gives 22 pets');
check([...document.querySelectorAll('.pet-card')].every(card=>(Number(card.dataset.student)-1)%4+1===2),'filtered pets belong to selected group');
check(document.getElementById('detail-group').textContent==='第 2 小组','hidden selection switches to first filtered pet');
run("groupFilter='all';currentSort='level';renderCollection()");
const sorted=run('fixtures.filter(s=>true).sort((a,b)=>b.level-a.level||b.exp-a.exp||a.id-b.id)');
check([...document.querySelectorAll('.pet-card')].every((card,i)=>Number(card.dataset.student)===sorted[i].id),'level and experience descending order');
run("currentSort='no';renderCollection()");
check([...document.querySelectorAll('.pet-card')].every((card,i)=>Number(card.dataset.student)===i+1),'student number ascending');
run("showView('login')");
check(!document.getElementById('login-view').hidden&&document.getElementById('display-view').hidden,'login view switch');
run("showView('hub')");
check(!document.getElementById('hub-view').hidden,'hub view switch');
check(!document.querySelector('.entry.primary'),'no permanent primary entry');
check(document.querySelector('#hub-view h1').textContent==='班级电子宠物管理系统 · 控制总台','original portal heading restored');
check(!!document.querySelector('.hub-heading [data-view="login"]'),'switch account remains in portal title area');
check(document.querySelectorAll('#hub-view .entry').length===2,'both portal entries retained');
check(!!document.querySelector('#login-view .hub-header'),'login shares portal header');
check(!!document.querySelector('#login-form #account')&&!!document.querySelector('#login-form #password'),'login fields retained');
check(document.querySelectorAll('.login-links [data-preview]').length===2,'create account and reset password retained');
check(css.includes('box-shadow:10px 10px 0 var(--portal-border)'),'shared hard shadow frame');
check(!html.includes('ACTIVE SESSION')&&!html.includes('PASSWORD'),'decorative text removed');
check(css.includes('grid-template-columns:repeat(4,minmax(0,1fr))'),'desktop grid caps at four');
check(css.includes('.grid-scroll{flex:1;min-height:0;overflow-y:auto'),'independent list scrolling');
check(css.includes('.card-art img{width:100%;height:100%'),'pet artwork fills stage');
check(!/localStorage|classPetRuntime|electronAPI|fetch\(/.test(js),'preview isolated from live app');
for(const id of ['login-view','hub-view']){
  const background=document.querySelector(`#${id} .paw-background`);
  check(!!background,`${id} has a paw background`);
  check(background.getAttribute('aria-hidden')==='true','decorations are hidden from assistive technology');
  const prints=[...background.querySelectorAll('.paw-print')];
  check(prints.length===10,'each background has ten paw prints');
  check(new Set(prints.map(print=>print.style.getPropertyValue('--paw-color'))).size===10,'each paw has its own solid color');
  check(prints.some(print=>print.classList.contains('cat'))&&prints.some(print=>print.classList.contains('dog')),'both cat and dog paws present');
  check(parseInt(prints[0].style.getPropertyValue('--paw-size'))>Math.max(...prints.slice(1).map(print=>parseInt(print.style.getPropertyValue('--paw-size')))),'top-left paw is largest');
}
check(!document.querySelector('#display-view .paw-background'),'pet display remains unchanged');
check(css.includes('pointer-events:none;user-select:none'),'background cannot intercept controls');
for(const kind of ['cat','dog'])check(fs.existsSync(path.join(root,`design/assets/${kind}-paw.svg`)),`${kind} paw asset exists`);
for(const image of document.querySelectorAll('img[src]'))check(fs.existsSync(path.resolve(root,'design',image.getAttribute('src'))),`missing asset ${image.getAttribute('src')}`);
for(const student of run('fixtures'))check(fs.existsSync(path.resolve(root,'design',run(`petImage(fixtures[${student.id-1}])`))),`missing pet image ${student.id}`);
console.log(`${checks} offline preview checks passed. Native visual and responsive checks remain manual.`);
